/** Is a theme dark (light text on a dark background)? */
export function isDarkTheme(th) {
  const m = /^#?([0-9a-f]{6})/i.exec(th?.background || '')
  if (!m) return true
  const n = parseInt(m[1], 16)
  return ((n >> 16) & 255) * 0.299 + ((n >> 8) & 255) * 0.587 + (n & 255) * 0.114 < 140
}
